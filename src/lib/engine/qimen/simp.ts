  穀: '谷', 滿: '满', 種: '种', 處: '处', 風: '风', 雲: '云',
  龍: '龙', 攝: '摄', 軒: '轩', 轅: '辕', 搖: '摇', 賊: '贼',
  籥: '钥', 師: '师', 國: '国', 關: '关', 時: '时', 節: '节',
